// rc/deploy/toolchain.hpp
//
// A toolchain file generated and checked, from lesson 20-02, graduated.
//
// from_triple makes a ToolchainSpec (system name, processor, compilers named <triple>-gcc and -g++, sysroot) from a target triple; render writes it as a CMake toolchain file, one setting to a line, with programs found on the host and libraries, headers and packages in the sysroot only; validate names what is wrong with a specification (an empty compiler, a system name or processor the triple does not imply, a sysroot that is relative, has a backslash or does not exist, and any -march=native, -mtune=native or -mcpu=native, which is the machine doing the build). find_library models the three modes: NEVER looks in the host's directories, ONLY in the target's, BOTH in the target's and then the host's.
//
// A spec for aarch64-linux-gnu with a sysroot and two flags rendered to 13 lines; a bad one gave 6 problems in a fixed order. With libusb only on the host, ONLY said missing and BOTH returned the x86_64 library; NEVER returned the host's libz where BOTH returned the target's.

