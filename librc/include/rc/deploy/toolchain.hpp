// What a CMake toolchain file says about a cross build.
struct ToolchainSpec {
  std::string triple;
  std::string system_name;      // CMAKE_SYSTEM_NAME: Linux, Windows or Generic
  std::string processor;        // CMAKE_SYSTEM_PROCESSOR
  std::string c_compiler;
  std::string cxx_compiler;
  std::string sysroot;          // the target's root of headers and libraries; empty for none
  std::vector<std::string> cxx_flags;
};

struct Problem {
  std::string field;
  std::string message;
};

// A specification made from a triple: the system name (Linux for linux, Windows for windows and mingw32, Generic for none), the processor (aarch64, arm for arm and armv7, and otherwise the architecture as written), the compilers
// named <triple>-gcc and <triple>-g++, and the sysroot given. An invalid triple gives a spec with an empty triple and nothing else filled in.
inline ToolchainSpec from_triple(const std::string& triple, const std::string& sysroot) {
  ToolchainSpec s;
  const rc::deploy::Target t = rc::deploy::parse_triple(triple);
  if (!t.valid) return s;
  s.triple = triple;
  s.system_name = t.os == "linux" ? "Linux" : (t.os == "windows" || t.os == "mingw32" ? "Windows" : "Generic");
  s.processor = (t.arch == "armv7" || t.arch == "arm") ? "arm" : t.arch;
  s.c_compiler = triple + "-gcc";
  s.cxx_compiler = triple + "-g++";
  s.sysroot = sysroot;
  return s;
}

namespace detail {
inline std::string quoted(const std::string& s) {
  std::string out = "\"";
  for (char c : s) {
    if (c == '"' || c == '\\') out += '\\';
    out += c;
  }
  return out + "\"";
}
inline bool absolute(const std::string& p) {
  if (!p.empty() && p[0] == '/') return true;
  return p.size() >= 3 && ((p[0] >= 'a' && p[0] <= 'z') || (p[0] >= 'A' && p[0] <= 'Z')) && p[1] == ':' && (p[2] == '/' || p[2] == '\\');
}
}  // namespace detail

// The text of the toolchain file, one setting to a line, in this order, every line ending in a newline:
//   # generated by rc::deploy, do not edit
//   set(CMAKE_SYSTEM_NAME <system_name>)
//   set(CMAKE_SYSTEM_PROCESSOR <processor>)
//   set(CMAKE_C_COMPILER <c_compiler>)
//   set(CMAKE_CXX_COMPILER <cxx_compiler>)
//   [if there is a sysroot:]  set(CMAKE_SYSROOT <sysroot>)  and  set(CMAKE_FIND_ROOT_PATH <sysroot>)
//   set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)      programs to run while building are the host's
//   set(CMAKE_FIND_ROOT_PATH_MODE_LIBRARY ONLY)       libraries, headers and packages are the target's, and only the target's
//   set(CMAKE_FIND_ROOT_PATH_MODE_INCLUDE ONLY)
//   set(CMAKE_FIND_ROOT_PATH_MODE_PACKAGE ONLY)
//   set(CMAKE_TRY_COMPILE_TARGET_TYPE STATIC_LIBRARY)   a trial build is not linked, since it could not run here anyway
//   [if there are flags:]  set(CMAKE_CXX_FLAGS_INIT "<flags joined by a space>")   (quoted, with " and \ escaped)
inline std::string render(const ToolchainSpec& s) {
  std::string out = "# generated by rc::deploy, do not edit\n";
  out += "set(CMAKE_SYSTEM_NAME " + s.system_name + ")\n";
  out += "set(CMAKE_SYSTEM_PROCESSOR " + s.processor + ")\n";
  out += "set(CMAKE_C_COMPILER " + s.c_compiler + ")\n";
  out += "set(CMAKE_CXX_COMPILER " + s.cxx_compiler + ")\n";
  if (!s.sysroot.empty()) {
    out += "set(CMAKE_SYSROOT " + s.sysroot + ")\n";
    out += "set(CMAKE_FIND_ROOT_PATH " + s.sysroot + ")\n";
  }
  out += "set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)\n";
  out += "set(CMAKE_FIND_ROOT_PATH_MODE_LIBRARY ONLY)\n";
  out += "set(CMAKE_FIND_ROOT_PATH_MODE_INCLUDE ONLY)\n";
  out += "set(CMAKE_FIND_ROOT_PATH_MODE_PACKAGE ONLY)\n";
  out += "set(CMAKE_TRY_COMPILE_TARGET_TYPE STATIC_LIBRARY)\n";
  if (!s.cxx_flags.empty()) {
    std::string joined;
    for (const std::string& f : s.cxx_flags) joined += (joined.empty() ? "" : " ") + f;
    out += "set(CMAKE_CXX_FLAGS_INIT " + detail::quoted(joined) + ")\n";
  }
  return out;
}

// What is wrong with a specification, in this order (each a Problem with the field named):
//  - "c_compiler" or "cxx_compiler" empty;
//  - "system_name" not the one the triple implies (see from_triple), or "processor" not the one it implies;
//  - "sysroot" (if given) not an absolute path, then containing a backslash, then (if `exists` says no) not existing;
//  - one "cxx_flags" Problem for each flag that is -march=native, -mtune=native or -mcpu=native, since "native" is the machine doing the building and not the robot.
// A triple that cannot be read is one Problem on "triple" and nothing else is checked.
using PathExists = std::function<bool(const std::string&)>;
inline std::vector<Problem> validate(const ToolchainSpec& s, const PathExists& exists) {
  std::vector<Problem> p;
  const rc::deploy::Target t = rc::deploy::parse_triple(s.triple);
  if (!t.valid) {
    p.push_back({"triple", "cannot be read"});
    return p;
  }
  if (s.c_compiler.empty()) p.push_back({"c_compiler", "empty"});
  if (s.cxx_compiler.empty()) p.push_back({"cxx_compiler", "empty"});
  const ToolchainSpec want = from_triple(s.triple, "");
  if (s.system_name != want.system_name) p.push_back({"system_name", "should be " + want.system_name});
  if (s.processor != want.processor) p.push_back({"processor", "should be " + want.processor});
  if (!s.sysroot.empty()) {
    if (!detail::absolute(s.sysroot)) p.push_back({"sysroot", "not an absolute path"});
    else if (s.sysroot.find('\\') != std::string::npos) p.push_back({"sysroot", "has a backslash"});
    else if (exists && !exists(s.sysroot)) p.push_back({"sysroot", "does not exist"});
  }
  for (const std::string& f : s.cxx_flags)
    if (f == "-march=native" || f == "-mtune=native" || f == "-mcpu=native") p.push_back({"cxx_flags", f + " is the machine doing the build"});
  return p;
}

// How CMake looks for a library: NEVER in the target's root directories (only the host's), ONLY in them, BOTH (the target's first, then the host's).
enum class FindMode { never, only, both };

struct Library {
  std::string path;      // where it is
  std::string arch;      // what it was built for
};

struct Found {
  bool found = false;
  Library library;
};

// Look for a library by file name: `roots` are the target's directories (the sysroot's), `host` the host's. NEVER looks in `host` only, ONLY in `roots` only, BOTH in `roots` and then `host`. The first match by file name wins.
inline Found find_library(const std::string& file, FindMode mode, const std::vector<Library>& roots, const std::vector<Library>& host) {
  auto look = [&file](const std::vector<Library>& where, Found& out) {
    for (const Library& l : where) {
      const std::size_t slash = l.path.rfind('/');
      const std::string name = slash == std::string::npos ? l.path : l.path.substr(slash + 1);
      if (name == file) {
        out.found = true;
        out.library = l;
        return;
      }
    }
  };
  Found f;
  if (mode != FindMode::never) look(roots, f);
  if (!f.found && mode != FindMode::only) look(host, f);
  return f;
}

